/**
 * The audited unit of work.
 *
 * `docs/architecture/02-control-plane.md` gives three reasons the control-plane
 * API should exist, and the first is that "audit records are written
 * server-side atomically with the mutation, so an operator-side network
 * failure cannot leave a mutation without an audit row". That property is what
 * this file makes structural rather than aspirational.
 *
 * Two callers now perform the same writes — the CLI and the admin UI. Keeping
 * "mutate, then remember to write the audit row, and remember to wrap both in
 * one transaction" as a convention each caller re-implements is how the two
 * drift. Instead:
 *
 *   - Every mutation is one exported `*WithAudit` function that owns its
 *     transaction.
 *   - `insertAuditRecord` and the bare writers are NOT exported from the
 *     package root (see `../index.ts`). There is no import path by which a
 *     caller can perform one of these mutations without its audit row.
 *   - A guarded UPDATE that matches nothing returns `applied: false` and
 *     writes **no** audit row. The log records transitions, not clicks — a
 *     re-run of "disable" on an already-disabled destination is not an event.
 *
 * Anything that throws inside the callback rolls both writes back together.
 */

import type { ActorSource } from "@polaris/shared-control-plane";
import type { Database } from "@polaris/shared-db";
import type { Kysely, Transaction } from "kysely";

import type { AuditEnvironment } from "../queries/audit-records.js";
import { insertAuditRecord } from "../queries/audit-records.js";

/**
 * Who is acting and why, for the audit row.
 *
 * `auditId` is generated by the caller so it can be logged and returned
 * before the transaction commits.
 */
export interface AuditContext {
  readonly auditId: string;
  readonly actorSource: ActorSource;
  readonly actorLabel: string;
  readonly reason?: string | null;
  readonly requestId?: string | null;
  readonly occurredAt: Date;
  /**
   * Snapshot overrides.
   *
   * Each mutation builds a sensible default from the row it already has, and
   * that is what the admin UI uses. Some callers know more: `destinations
   * create` holds the full operator input, `keys create` the issuance
   * context. Rather than have those callers lose detail — or have this
   * package grow a parameter per command to reconstruct it — they pass the
   * snapshot they already built.
   *
   * The transaction, the guard, and the decision of whether to write a row at
   * all stay here regardless. Only the payload is negotiable.
   */
  readonly before?: unknown;
  readonly after?: unknown;
}

/**
 * Outcome of an audited mutation.
 *
 * `applied: false` means the guarded UPDATE matched nothing — the row was
 * already in the target state. Callers surface this as "already disabled"
 * rather than as an error, matching the CLI's idempotent-toggle behaviour.
 */
export interface MutationOutcome {
  readonly applied: boolean;
  /** Present only when `applied` is true — no row is written otherwise. */
  readonly auditId: string | null;
}

const NOT_APPLIED: MutationOutcome = { applied: false, auditId: null };

/** Row identity and snapshots for the audit record. */
export interface AuditTarget {
  readonly action: string;
  readonly targetType: string;
  readonly targetId: string;
  readonly projectId?: string | null;
  readonly environment?: AuditEnvironment | null;
  readonly before?: unknown;
  readonly after?: unknown;
}

/**
 * Run `mutate` and its audit row in one transaction.
 *
 * Internal: exported for the `*WithAudit` functions in this directory, not
 * from the package root. Callers get the named mutations, never this.
 */
export async function withAudit(
  db: Kysely<Database>,
  audit: AuditContext,
  target: AuditTarget,
  mutate: (trx: Transaction<Database>) => Promise<boolean>,
): Promise<MutationOutcome> {
  return db.transaction().execute(async (trx) => {
    const applied = await mutate(trx);
    if (!applied) return NOT_APPLIED;

    await insertAuditRecord(trx, {
      audit_id: audit.auditId,
      actor_source: audit.actorSource,
      actor_label: audit.actorLabel,
      action: target.action,
      target_type: target.targetType,
      target_id: target.targetId,
      project_id: target.projectId ?? null,
      environment: target.environment ?? null,
      // Caller override wins; otherwise the mutation's own snapshot.
      before: audit.before !== undefined ? audit.before : (target.before ?? null),
      after: audit.after !== undefined ? audit.after : (target.after ?? null),
      reason: audit.reason ?? null,
      // The CLI stamps request_id = audit_id because it has no request. The
      // API passes its own UUIDv7 request id, which makes audit rows joinable
      // against the service logs.
      request_id: audit.requestId ?? audit.auditId,
      created_at: audit.occurredAt,
    });

    return { applied: true, auditId: audit.auditId };
  });
}
