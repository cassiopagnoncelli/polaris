#!/usr/bin/env node
/**
 * Polaris project-config schema-artifact generator.
 *
 * Each participating component exports, from its BUILT entry (`dist/index.js`):
 *
 *   export const PROJECT_CONFIG_NAMESPACE = "sessionizer";
 *   export const projectConfigSchema = z.object({ ... });
 *   export const instanceConfigSchema = z.object({ ... }); // optional
 *
 * This script converts those Zod schemas (the source of truth, living in the
 * component's code) into checked-in JSON Schema artifacts under
 * `libs/tenancy/config-schemas`, the generated surface the control plane
 * (typed admin forms, `polaris config validate`) imports. The doctrine is the
 * `.env.example` header's line: "if it drifts, the schemas win."
 *
 * Usage:
 *
 *   pnpm config-schemas          # regenerate libs/tenancy/config-schemas
 *   pnpm config-schemas:check    # regenerate to memory and diff against disk
 *
 * Or, programmatically:
 *
 *   node scripts/project-config-schemas-generate.mjs [--check]
 *
 * Exit codes:
 *   0   success / no drift, no compatibility violation
 *   1   drift or breaking schema change detected (in --check), or failure
 *
 * `--check` enforces two properties:
 *
 *   1. Byte-identical drift: the regenerated artifacts must match the
 *      checked-in files exactly (same contract as `openapi-generate.mjs`).
 *   2. Additive-only compatibility (plan §3.4): against the version of each
 *      artifact in git HEAD, a property may not be removed, may not change
 *      its `type`, and may not become required without a `default`. A
 *      breaking config change must fail its own PR, not a rolling deploy.
 *
 * Polaris hard-rule: the script imports each registry component's compiled
 * `dist/` entry, so it first runs a dependency-aware filtered build
 * (`pnpm -r --if-present --filter "<pkg>..." run build` — the `...` suffix
 * builds the component's workspace dependencies too; see commit 6e67a78).
 * With an empty registry no build runs at all.
 *
 * @see docs/implementation/project-config-plan.md §3.1, §3.4
 * @see scripts/openapi-generate.mjs (the pattern this mirrors)
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { z } from "zod";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO_ROOT = resolve(__dirname, "..");

/** POSIX-style path of the generated package, used for git paths and logs. */
const PACKAGE_REL = "libs/tenancy/config-schemas";
const PACKAGE_DIR = resolve(REPO_ROOT, "libs", "tenancy", "config-schemas");

