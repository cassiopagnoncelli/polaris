/** Header stamped into every generated file. */
const GENERATED_HEADER = "GENERATED by scripts/project-config-schemas-generate.mjs — do not edit.";

/**
 * Biome's configured line width (biome.json). The JSON and TS printers below
 * inline an array only when it fits, which is exactly what Biome's formatter
 * does — the generated files must survive `pnpm format:check` byte-for-byte.
 */
const LINE_WIDTH = 100;

// ---------------------------------------------------------------------------
// Pure core — everything below returns strings from values; no I/O, no Date.
// ---------------------------------------------------------------------------

/**
 * Convert one Zod schema to a canonical JSON Schema document.
 *
 * `io: "input"` describes what an operator must SUPPLY: keys with a
 * `.default()` are optional inputs, so `required` lists only the keys that
 * have no default — the exact contract `polaris config validate` and the
 * compat rules below need. (The default `io: "output"` would list every key
 * as required and stamp `additionalProperties: false`, contradicting the
 * strip-mode doctrine of plan §3.5.) `.meta({ secret: true })` survives the
 * conversion as a plain `secret: true` on the property — verified against
 * the workspace's zod 4.4.3.
 */
function convertSchema(schema) {
  return canonicalize(z.toJSONSchema(schema, { io: "input" }));
}

/** Recursively sort object keys so two runs produce identical bytes. */
function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value !== null && typeof value === "object") {
    const out = {};
    for (const key of Object.keys(value).sort()) out[key] = canonicalize(value[key]);
    return out;
  }
  return value;
}

function isRecord(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

/** Top-level property names marked `.meta({ secret: true })` in the schema. */
function extractSecretKeys(document) {
  const properties = isRecord(document.properties) ? document.properties : {};
  return Object.keys(properties)
    .filter((key) => isRecord(properties[key]) && properties[key].secret === true)
    .sort();
}

/**
 * Print a JSON document the way Biome's JSON formatter would: 2-space
 * indent, objects always expanded, arrays inlined when the line fits.
 * (JSON files carry no trailing commas.)
 */
function printJsonDocument(value) {
  return `${printJson(value, 0, 0)}\n`;
}

function printJson(value, indentLevel, usedCols) {
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    const flat = tryFlat(value);
    if (flat !== null && usedCols + flat.length <= LINE_WIDTH) return flat;
    const pad = "  ".repeat(indentLevel + 1);
    const items = value.map((item) => pad + printJson(item, indentLevel + 1, pad.length));
    return `[\n${items.join(",\n")}\n${"  ".repeat(indentLevel)}]`;
  }
  if (isRecord(value)) {
    const keys = Object.keys(value);
    if (keys.length === 0) return "{}";
    const pad = "  ".repeat(indentLevel + 1);
    const lines = keys.map((key) => {
      const prefix = `${pad}${JSON.stringify(key)}: `;
      return prefix + printJson(value[key], indentLevel + 1, prefix.length);
    });
    return `{\n${lines.join(",\n")}\n${"  ".repeat(indentLevel)}}`;
  }
  return JSON.stringify(value);
}

/**
 * Flat single-line rendering of a value, or null when it contains a
 * non-empty object — this printer always expands those, and Biome preserves
 * an expanded object, so an array holding one can never be inlined.
 */
function tryFlat(value) {
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    const parts = [];
    for (const item of value) {
      const flat = tryFlat(item);
      if (flat === null) return null;
      parts.push(flat);
    }
    return `[${parts.join(", ")}]`;
  }
  if (isRecord(value)) return Object.keys(value).length === 0 ? "{}" : null;
  return JSON.stringify(value);
}

/**
 * Print a JSON value as a TypeScript literal the way Biome's JS formatter
 * would: double quotes, keys quoted only when not valid identifiers
 * (`quoteProperties: "asNeeded"`), trailing commas in multiline lists
 * (`trailingCommas: "all"`), arrays inlined when the line fits.
 */
function printTsValue(value, indentLevel, usedCols) {
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    const flat = tryFlat(value);
    if (flat !== null && usedCols + flat.length <= LINE_WIDTH) return flat;
    const pad = "  ".repeat(indentLevel + 1);
    const items = value.map((item) => pad + printTsValue(item, indentLevel + 1, pad.length));
    return `[\n${items.join(",\n")},\n${"  ".repeat(indentLevel)}]`;
  }
  if (isRecord(value)) {
    const keys = Object.keys(value);
    if (keys.length === 0) return "{}";
    const pad = "  ".repeat(indentLevel + 1);
    const lines = keys.map((key) => {
      const prefix = `${pad}${tsKey(key)}: `;
      return prefix + printTsValue(value[key], indentLevel + 1, prefix.length);
    });
    return `{\n${lines.join(",\n")},\n${"  ".repeat(indentLevel)}}`;
  }
  return JSON.stringify(value);
}

function tsKey(key) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

/** The generated `src/index.ts` source for the given prepared entries. */
function buildIndexSource(entries) {
  const lines = [
    `// ${GENERATED_HEADER}`,
    "//",
    "// Regenerate with `pnpm config-schemas`; `pnpm config-schemas:check` and the",
    "// scripts test suite fail when this file drifts from the component schemas.",
    "",
    "/** A JSON Schema document as produced by zod v4's `z.toJSONSchema`. */",
    "export type JsonSchema = Record<string, unknown>;",
    "",
    "/** The generated schema surface for one component namespace. */",
    "export interface ProjectConfigSchemaEntry {",
    "  project: JsonSchema;",
    "  instance?: JsonSchema;",
    "  secretKeys: {",
    "    project: string[];",
    "    instance: string[];",
    "  };",
    "}",
    "",
    "/**",
    " * Project-config schema artifacts, keyed by component namespace.",
    " *",
    " * Generated from each participating component's exported Zod schemas;",
    " * secret-typed keys carry `secret: true` and are listed in `secretKeys`.",
    " * One entry per component that has cut over to project configuration;",
    " * empty before the first cutover lands.",
    " */",
  ];
  if (entries.length === 0) {
    lines.push(
      "export const PROJECT_CONFIG_SCHEMAS: Record<string, ProjectConfigSchemaEntry> = {};",
    );
    lines.push("");
    return lines.join("\n");
  }
  lines.push("export const PROJECT_CONFIG_SCHEMAS: Record<string, ProjectConfigSchemaEntry> = {");
  for (const entry of entries) {
    lines.push(`  ${tsKey(entry.namespace)}: {`);
    lines.push(`    project: ${printTsValue(entry.project, 2, "    project: ".length)},`);
    if (entry.instance !== undefined) {
      lines.push(`    instance: ${printTsValue(entry.instance, 2, "    instance: ".length)},`);
    }
    lines.push("    secretKeys: {");
    lines.push(
      `      project: ${printTsValue(entry.secretKeys.project, 3, "      project: ".length)},`,
    );
    lines.push(
      `      instance: ${printTsValue(entry.secretKeys.instance, 3, "      instance: ".length)},`,
    );
    lines.push("    },");
    lines.push("  },");
  }
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

/**
 * The pure core: turn `{ namespace, projectSchema, instanceSchema? }` entries
 * into the generated file map `{ relativePath: contents }`, relative to
 * `libs/tenancy/config-schemas`. Deterministic by construction — object
 * keys are sorted and nothing reads the clock.
 */
export function buildArtifacts(entries) {
  const sorted = [...entries].sort((a, b) => a.namespace.localeCompare(b.namespace));
  const seen = new Set();
  const files = {};
  const indexEntries = [];
  for (const entry of sorted) {
    if (seen.has(entry.namespace)) {
      throw new Error(`duplicate namespace "${entry.namespace}" in registry entries`);
    }
    seen.add(entry.namespace);
    const project = convertSchema(entry.projectSchema);
    const instance =
      entry.instanceSchema === undefined ? undefined : convertSchema(entry.instanceSchema);
    const secretKeys = {
      project: extractSecretKeys(project),
      instance: instance === undefined ? [] : extractSecretKeys(instance),
    };
    files[`schemas/${entry.namespace}.project.schema.json`] = printJsonDocument(
      canonicalize({ ...project, $comment: GENERATED_HEADER }),
    );
    if (instance !== undefined) {
      files[`schemas/${entry.namespace}.instance.schema.json`] = printJsonDocument(
        canonicalize({ ...instance, $comment: GENERATED_HEADER }),
      );
    }
    indexEntries.push({ namespace: entry.namespace, project, instance, secretKeys });
  }
  files["src/index.ts"] = buildIndexSource(indexEntries);
  const map = {};
  for (const path of Object.keys(files).sort()) map[path] = files[path];
  return map;
}

/**
 * Removals that are deliberate, reviewed, and safe — the one exception to
 * additive-only.
 *
 * Keep this list SHORT and each entry specific. The rule exists because an
 * operator may already have set the key: removing it drops a value they chose,
 * silently, from a panel that will no longer show it. An entry here is a claim
 * that the removal cannot do that, and the reason has to say why.
 *
 * "Nobody uses it yet" is NOT a reason — that is unknowable from here. The only
 * reason that holds is that the key never had an effect to lose.
 */
const REMOVAL_EXCEPTIONS = new Map([
  [
    "meta-capi::allow_replay",
    "declared and read by nothing: replay suppression runs in the destination " +
      "runtime before the deliverer the config slice reaches, so a stored value " +
      "never had an effect to drop. Redundant with destinations.replay_opt_in. " +
      "`scripts/lint-project-config-keys.mjs` now fails on a key in this state.",
  ],
]);

/**
 * The additive-only compatibility rules of plan §3.4, applied to two JSON
 * Schema documents (the HEAD artifact vs the regenerated one). Returns
 * violations `{ key, rule, message }`; an empty array means compatible.
 *
 * Within a namespace config evolution is additive-only: a property may not
 * be removed, may not change its `type`, and may not be (or become) required
 * without a `default`. New optional properties and new properties with
 * defaults pass. A change that needs to break the contract takes a new
 * namespace instead — unless it appears in {@link REMOVAL_EXCEPTIONS}, which
 * `namespace` is needed to consult.
 */
export function checkCompat(previous, next, namespace) {
  const violations = [];
  const prevProps = isRecord(previous) && isRecord(previous.properties) ? previous.properties : {};
  const nextProps = isRecord(next) && isRecord(next.properties) ? next.properties : {};
  for (const key of Object.keys(prevProps).sort()) {
    const prevProp = prevProps[key];
    const nextProp = nextProps[key];
    if (nextProp === undefined) {
      if (namespace !== undefined && REMOVAL_EXCEPTIONS.has(`${namespace}::${key}`)) continue;
      violations.push({
        key,
        rule: "removed",
        message: `property "${key}" was removed — config evolution is additive-only within a namespace`,
      });
      continue;
    }
    const prevType = JSON.stringify(isRecord(prevProp) ? prevProp.type : undefined) ?? "undefined";
    const nextType = JSON.stringify(isRecord(nextProp) ? nextProp.type : undefined) ?? "undefined";
    if (prevType !== nextType) {
      violations.push({
        key,
        rule: "type-changed",
        message: `property "${key}" changed type ${prevType} -> ${nextType} — a breaking change takes a new namespace`,
      });
    }
  }
  const prevRequired = new Set(
    isRecord(previous) && Array.isArray(previous.required) ? previous.required : [],
  );
  const nextRequired = isRecord(next) && Array.isArray(next.required) ? next.required : [];
  for (const key of [...nextRequired].sort()) {
    if (prevRequired.has(key)) continue;
    const prop = nextProps[key];
    if (isRecord(prop) && "default" in prop) continue;
    violations.push({
      key,
      rule: "required-without-default",
      message: `property "${key}" is newly required and has no default — existing projects would break on a rolling deploy`,
    });
  }
  return violations;
}

// ---------------------------------------------------------------------------
// Shell — builds and imports registry components, touches disk and git.
// ---------------------------------------------------------------------------

/**
 * Build one registry component together with its workspace dependencies.
 * The `...` filter suffix is load-bearing: without it pnpm builds only the
 * named package against stale or missing dependency dists (commit 6e67a78).
 */
function buildRegistryPackage(packageName) {
  const result = spawnSync(
    "pnpm",
    ["-r", "--if-present", "--filter", `${packageName}...`, "run", "build"],
    { cwd: REPO_ROOT, stdio: "inherit" },
  );
  if (result.status !== 0) {
    throw new Error(
      `build failed for ${packageName} (pnpm exited ${result.status ?? "by signal"})`,
    );
  }
}

/** Import every registry component's built entry and collect its schemas. */
async function loadRegistryEntries() {
  const entries = [];
  for (const item of REGISTRY) {
    buildRegistryPackage(item.packageName);
    const distPath = resolve(REPO_ROOT, item.distEntry);
    if (!existsSync(distPath)) {
      throw new Error(
        [
          `${item.packageName} dist entry is missing after its build.`,
          `Looked at: ${distPath}`,
          "Check the registry row's distEntry against the package's tsconfig outDir.",
        ].join("\n"),
      );
    }
    const mod = await import(pathToFileURL(distPath).href);
    if (mod.PROJECT_CONFIG_NAMESPACE !== item.namespace) {
      throw new Error(
        `${item.packageName} exports PROJECT_CONFIG_NAMESPACE ${JSON.stringify(
          mod.PROJECT_CONFIG_NAMESPACE,
        )} but the registry says ${JSON.stringify(item.namespace)}.`,
      );
    }
    if (mod.projectConfigSchema === undefined) {
      throw new Error(
        `${item.packageName} does not export projectConfigSchema; the participation convention requires it.`,
      );
    }
    entries.push({
      namespace: item.namespace,
      projectSchema: mod.projectConfigSchema,
      instanceSchema: mod.instanceConfigSchema,
    });
  }
  return entries;
}

/** Generated schema artifacts currently on disk, as package-relative paths. */
function listDiskSchemaArtifacts() {
  const dir = join(PACKAGE_DIR, "schemas");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.endsWith(".schema.json"))
    .map((name) => `schemas/${name}`)
    .sort();
}

/** Contents of `HEAD:<repo path>`, or undefined when absent (a new file). */
function gitShowHead(repoRelativePath) {
  const result = spawnSync("git", ["show", `HEAD:${repoRelativePath}`], {
    cwd: REPO_ROOT,
    encoding: "utf8",
  });
  if (result.status !== 0) return undefined;
  return result.stdout;
}

function hasGitHead() {
  const result = spawnSync("git", ["rev-parse", "--verify", "HEAD"], {
    cwd: REPO_ROOT,
    stdio: "ignore",
  });
  return result.status === 0;
}

function parseArgs(argv) {
  const args = { check: false };
  for (let i = 2; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--check") {
      args.check = true;
    } else if (arg === "--help" || arg === "-h") {
      process.stdout.write(
        [
          "Usage: node scripts/project-config-schemas-generate.mjs [--check]",
          "",
          "  --check   Regenerate to memory and diff against the checked-in package.",
          "            Also enforces the additive-only compatibility rules against",
          "            git HEAD. Exits non-zero on drift or violation; useful in CI.",
          "",
        ].join("\n"),
      );
      process.exit(0);
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return args;
}

function readIfExists(path) {
  if (!existsSync(path)) return undefined;
  return readFileSync(path, "utf8");
}

function writeMode(files) {
  for (const [relPath, contents] of Object.entries(files)) {
    const absPath = join(PACKAGE_DIR, relPath);
    mkdirSync(dirname(absPath), { recursive: true });
    writeFileSync(absPath, contents, "utf8");
    process.stdout.write(`Wrote ${PACKAGE_REL}/${relPath}\n`);
  }
  for (const relPath of listDiskSchemaArtifacts()) {
    if (files[relPath] !== undefined) continue;
    rmSync(join(PACKAGE_DIR, relPath));
    process.stdout.write(`Pruned stale ${PACKAGE_REL}/${relPath}\n`);
  }
}

function checkMode(files) {
  const drifted = [];
  for (const [relPath, contents] of Object.entries(files)) {
    const existing = readIfExists(join(PACKAGE_DIR, relPath));
    if (existing === undefined) {
      drifted.push(`${PACKAGE_REL}/${relPath} (missing)`);
    } else if (existing !== contents) {
      drifted.push(`${PACKAGE_REL}/${relPath}`);
    }
  }
  for (const relPath of listDiskSchemaArtifacts()) {
    if (files[relPath] === undefined) drifted.push(`${PACKAGE_REL}/${relPath} (stale)`);
  }

  const violations = [];
  if (hasGitHead()) {
    for (const relPath of Object.keys(files)) {
      if (!relPath.endsWith(".schema.json")) continue;
      const repoPath = `${PACKAGE_REL}/${relPath}`;
      const previousRaw = gitShowHead(repoPath);
      if (previousRaw === undefined) continue; // new artifact — fine
      let previous;
      try {
        previous = JSON.parse(previousRaw);
      } catch (err) {
        throw new Error(`HEAD:${repoPath} is not valid JSON: ${String(err)}`);
      }
      // The namespace is the artifact's filename stem, which is how
      // REMOVAL_EXCEPTIONS is keyed.
      const namespace = relPath.replace(/^schemas\//, "").replace(/\.project\.schema\.json$/, "");
      for (const violation of checkCompat(previous, JSON.parse(files[relPath]), namespace)) {
        violations.push(`  ${repoPath} :: ${violation.key} — ${violation.message}`);
      }
    }
  } else {
    process.stderr.write("warning: no git HEAD; skipping the additive-only compatibility check\n");
  }

  if (drifted.length > 0 || violations.length > 0) {
    const sections = [];
    if (drifted.length > 0) {
      sections.push(
        [
          "Project-config schema drift detected. Re-run `pnpm config-schemas` and commit the result.",
          "",
          ...drifted.map((path) => `  drifted: ${path}`),
        ].join("\n"),
      );
    }
    if (violations.length > 0) {
      sections.push(
        [
          "Breaking project-config schema change (additive-only rule, plan §3.4):",
          "",
          ...violations,
        ].join("\n"),
      );
    }
    process.stderr.write(`${sections.join("\n\n")}\n`);
    process.exit(1);
  }
  process.stdout.write(`Project-config schemas in sync: ${PACKAGE_REL}\n`);
}

async function main() {
  const args = parseArgs(process.argv);
  const entries = await loadRegistryEntries();
  const files = buildArtifacts(entries);
  if (args.check) {
    checkMode(files);
    return;
  }
  writeMode(files);
}

// Allow the script to be imported by tests without running main().
const invokedDirectly =
  import.meta.url === `file://${process.argv[1]}` ||
  fileURLToPath(import.meta.url) === process.argv[1];

if (invokedDirectly) {
  main().catch((err) => {
    process.stderr.write(`${err instanceof Error ? err.message : String(err)}\n`);
    process.exit(1);
  });
}
